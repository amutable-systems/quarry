package httpsig

import (
	"fmt"
	"net/http"
	"strconv"
)

// message is a message whose components can be covered.
type message interface {
	// request returns the request for request-derived components.
	request() (*http.Request, error)
	// statusCode returns the status for @status.
	statusCode() (int, error)
	// fieldValues returns the line values of a header (or trailer) field, or
	// false if the message does not have it.
	fieldValues(name string, trailer bool) ([]string, bool, error)
	// related returns the message that ";req" refers to.
	related() (message, error)
}

// requestMessage is an outgoing request, as net/http will send it.
type requestMessage struct {
	req *http.Request
}

func (m requestMessage) request() (*http.Request, error) {
	return m.req, nil
}

func (requestMessage) statusCode() (int, error) {
	return 0, ErrResponseOnlyComponent
}

func (requestMessage) related() (message, error) {
	return nil, ErrResponseOnlyComponent
}

func (m requestMessage) fieldValues(name string, trailer bool) ([]string, bool, error) {
	switch name {
	case "host":
		return nil, false, fmt.Errorf("%w: cover @authority instead of host", ErrInvalidComponent)
	case "transfer-encoding", "trailer":
		return nil, false, fmt.Errorf("%w: %s is generated by the transport", ErrInvalidComponent, name)
	}
	if trailer {
		values := m.req.Trailer.Values(name)
		return values, values != nil, nil
	}
	if name == "content-length" {
		// net/http ignores Content-Length in Header and writes its own.
		length, ok := m.contentLength()
		if !ok {
			return nil, false, nil
		}
		return []string{strconv.FormatInt(length, 10)}, true, nil
	}
	values := m.req.Header.Values(name)
	return values, values != nil, nil
}

// contentLength returns the Content-Length net/http will send, or false if it
// will not send one or its value cannot be known before sending.
func (m requestMessage) contentLength() (int64, bool) {
	req := m.req
	if len(req.TransferEncoding) > 0 {
		return 0, false
	}
	if req.Body == nil || req.Body == http.NoBody {
		// HTTP/1.1 and HTTP/2 both send a zero length for these methods.
		switch req.Method {
		case http.MethodPost, http.MethodPut, http.MethodPatch:
			return 0, true
		}
		return 0, false
	}
	if req.ContentLength > 0 {
		return req.ContentLength, true
	}
	return 0, false
}
